/**
 * Desktop → Android connection sharing.
 *
 * Desktop: a "Share connection" button shows the stored connection as a QR
 * code. Rust renders the SVG, so the page never holds the key as text; the QR
 * is cleared from the DOM on close and auto-hidden after a minute because it
 * is a bearer secret, not a picture.
 *
 * Android: a scanned `hitl-inbox://` link arrives through MainActivity and is
 * claimed once from Rust. The confirmation shows *where* the code points
 * (server and topic) before anything is saved — that is both the overwrite
 * warning and the anti-phishing check. The key is never displayed.
 */
const SHARE_AUTOHIDE_MS = 60_000;
const IMPORT_POLL_MS = 3_000;

export function createConnectionShare({ invoke, shareButton, shareDialog, importDialog, onImported }) {
    const qrBox = shareDialog?.querySelector('.share-qr');
    const shareError = shareDialog?.querySelector('.share-error');
    const countdown = shareDialog?.querySelector('.share-countdown');
    const importServer = importDialog?.querySelector('.import-server');
    const importTopic = importDialog?.querySelector('.import-topic');
    const importError = importDialog?.querySelector('.import-error');
    const importConfirm = importDialog?.querySelector('.import-confirm');
    const importOverwriteNote = importDialog?.querySelector('.import-overwrite-note');
    let hideTimer = null;
    let tickTimer = null;
    let pendingUri = null;
    let checking = false;
    let configured = false;

    function closeShare() {
        if (hideTimer) clearTimeout(hideTimer);
        if (tickTimer) clearInterval(tickTimer);
        hideTimer = tickTimer = null;
        if (shareDialog?.open) shareDialog.close();
        // The QR *is* the credentials; do not leave it in the DOM.
        if (qrBox) qrBox.replaceChildren();
    }

    async function openShare() {
        if (!shareDialog) return;
        if (shareError) shareError.textContent = '';
        try {
            const svg = await invoke('share_connection_qr');
            if (qrBox) {
                // Trusted input: generated by our own Rust side, not user data.
                qrBox.innerHTML = svg;
            }
            if (!shareDialog.open) shareDialog.showModal();
            let remaining = SHARE_AUTOHIDE_MS / 1000;
            if (countdown) countdown.textContent = `Hiding in ${remaining}s.`;
            tickTimer = setInterval(() => {
                remaining -= 1;
                if (countdown) countdown.textContent = `Hiding in ${remaining}s.`;
            }, 1000);
            hideTimer = setTimeout(closeShare, SHARE_AUTOHIDE_MS);
        } catch (reason) {
            if (shareError) shareError.textContent = String(reason?.message ?? reason);
            if (!shareDialog.open) shareDialog.showModal();
            hideTimer = setTimeout(closeShare, SHARE_AUTOHIDE_MS);
        }
    }

    function closeImport() {
        pendingUri = null;
        if (importDialog?.open) importDialog.close();
        if (importError) importError.textContent = '';
    }

    async function checkPendingImport() {
        if (checking || importDialog?.open) return;
        checking = true;
        try {
            const uri = await invoke('take_pending_import');
            if (!uri) return;
            const preview = await invoke('inspect_connection_import', { uri });
            pendingUri = uri;
            if (importServer) importServer.textContent = preview.server;
            if (importTopic) importTopic.textContent = preview.topicId;
            if (importError) importError.textContent = '';
            if (importOverwriteNote) importOverwriteNote.hidden = !configured;
            if (importConfirm) importConfirm.textContent = configured ? 'Replace connection' : 'Import connection';
            if (importDialog && !importDialog.open) importDialog.showModal();
        } catch (reason) {
            // A bad or hostile code never reaches the save path; say why and
            // offer only a way out, with nothing to confirm.
            pendingUri = null;
            if (importServer) importServer.textContent = '—';
            if (importTopic) importTopic.textContent = '—';
            if (importError) importError.textContent = String(reason?.message ?? reason);
            if (importOverwriteNote) importOverwriteNote.hidden = true;
            if (importConfirm) {
                importConfirm.textContent = 'Import connection';
                importConfirm.disabled = true;
            }
            if (importDialog && !importDialog.open) importDialog.showModal();
        } finally {
            checking = false;
        }
    }

    shareButton?.addEventListener('click', openShare);
    shareDialog?.querySelector('.share-close')?.addEventListener('click', closeShare);
    shareDialog?.addEventListener('close', () => {
        if (hideTimer) clearTimeout(hideTimer);
        if (tickTimer) clearInterval(tickTimer);
        if (qrBox) qrBox.replaceChildren();
    });
    importDialog?.querySelector('.import-cancel')?.addEventListener('click', closeImport);
    importConfirm?.addEventListener('click', async () => {
        if (!pendingUri) return;
        importConfirm.disabled = true;
        if (importError) importError.textContent = '';
        try {
            await invoke('import_connection', { uri: pendingUri });
            configured = true;
            closeImport();
            onImported?.();
        } catch (reason) {
            if (importError) importError.textContent = String(reason?.message ?? reason);
        } finally {
            importConfirm.disabled = false;
        }
    });
    // Re-enable the confirm button whenever a fresh code is being presented.
    importDialog?.addEventListener('close', () => {
        if (importConfirm) importConfirm.disabled = false;
    });

    async function initialize() {
        let settings;
        try {
            settings = await invoke('get_connection_settings');
        } catch {
            settings = { mobile: false, configured: false };
        }
        configured = Boolean(settings.configured);

        // Sharing is a desktop affordance; the phone imports instead.
        if (shareButton) shareButton.hidden = settings.mobile || !settings.configured;
        if (!settings.mobile) return;

        await checkPendingImport();
        setInterval(checkPendingImport, IMPORT_POLL_MS);
        // Warm start: the link arrives while the app is backgrounded, and the
        // scan brings it back to the front.
        document.addEventListener('visibilitychange', () => {
            if (!document.hidden) checkPendingImport();
        });
        window.addEventListener('focus', checkPendingImport);
    }

    return { initialize };
}
